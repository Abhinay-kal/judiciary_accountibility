    # =========================================================================
    # EXPORT COORDINATION
    # =========================================================================

    @staticmethod
    def export_rti_request(
        rti_request_text: str,
        pio_address: str,
        applicant_name: str,
        case_number: str,
        export_format: str = RTIExportFormat.TXT,
    ) -> Tuple[bool, str]:
        """
        Unified export function for different formats.
        
        Args:
            rti_request_text: Generated RTI text
            pio_address: PIO address
            applicant_name: Applicant name
            case_number: Case reference number
            export_format: Format (txt, html, markdown, postal)
            
        Returns:
            (success, exported_content)
        """
        try:
            if export_format == RTIExportFormat.TXT:
                content = RTIExporter.export_as_text(
                    rti_request_text, pio_address, applicant_name, case_number
                )
            
            elif export_format == RTIExportFormat.HTML:
                content = RTIExporter.export_as_html(
                    rti_request_text, pio_address, applicant_name, case_number
                )
            
            elif export_format == RTIExportFormat.POSTAL:
                content = RTIExporter.export_as_postal_format(
                    rti_request_text, pio_address,
                    "[Your Full Address]",
                    applicant_name, case_number
                )
            
            elif export_format == "markdown":
                content = RTIExporter.export_as_markdown(
                    rti_request_text, pio_address, applicant_name, case_number
                )
            
            else:
                return False, f"Unsupported format: {export_format}"
            
            return True, content
        
        except Exception as e:
            return False, f"Export error: {str(e)}"

